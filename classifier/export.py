"""
classifier/export.py - trained Keras model -> full-int8 TensorFlow Lite model + C array for the ESP32.

    python -m classifier.export                                   # best run in classifier/runs/
    python -m classifier.export --run classifier/runs/s10_cp0.8 --sessions 10

Writes into the run folder:
    model_int8.tflite        int8 weights and activations (TFLite Micro on the ESP32)
    model_data.h             the same bytes as a C array (copied into firmware/esp32_cam_classifier/)
    export.json              size, int8-vs-float agreement, accuracy, MACs, activation memory estimate
    model_np.npz             float weights (BN folded) for classifier/npmodel.py - the twin app's classifier
Model I/O on the device: input int8 [1,64,64,3] RGB = pixel - 128 (scale 1, zero point -128, checked below),
output int8 [1,4] class scores (dequantise with the output scale / zero point, also written to the header).
"""
import argparse
import json
import os

import numpy as np

from classifier import live, preprocess as pp
from classifier.train import ROOT, load


def float_input_model(model):
    """Same layers, float32 input (0..255) - the converter quantises the input itself."""
    import keras
    n = model.input_shape[1]
    x = inp = keras.Input((n, n, 3), dtype="float32", batch_size=1)
    for layer in model.layers[1:]:
        x = layer(x)
    return keras.Model(inp, x)


def convert(model, X):
    import tensorflow as tf
    m = float_input_model(model)
    fn = tf.function(lambda x: m(x, training=False))
    conc = fn.get_concrete_function(tf.TensorSpec([1] + list(X.shape[1:]), tf.float32))
    conv = tf.lite.TFLiteConverter.from_concrete_functions([conc], m)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]

    def rep():
        for i in np.random.default_rng(0).permutation(len(X))[:200]:
            yield [X[i:i + 1].astype(np.float32)]
    conv.representative_dataset = rep
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    return conv.convert()


def run_tflite(blob, X):
    import tensorflow as tf
    it = tf.lite.Interpreter(model_content=blob)
    it.allocate_tensors()
    i, o = it.get_input_details()[0], it.get_output_details()[0]
    (si, zi), (so, zo) = i["quantization"], o["quantization"]
    out = []
    for x in X:
        q = np.clip(np.round(x.astype(np.float32) / si + zi), -128, 127).astype(np.int8)
        it.set_tensor(i["index"], q[None])
        it.invoke()
        out.append((it.get_tensor(o["index"])[0].astype(np.float32) - zo) * so)
    return np.array(out), (si, zi), (so, zo), it


def macs(model):
    total = 0
    for layer in model.layers:
        if layer.__class__.__name__ == "Conv2D":
            _, h, w, cout = layer.output.shape
            kh, kw = layer.kernel_size
            total += h * w * cout * kh * kw * layer.input.shape[-1]
        elif layer.__class__.__name__ == "Dense":
            total += layer.input.shape[-1] * layer.units
    return int(total)


def activation_peak(it):
    """Rough tensor-arena size: biggest (input + output) pair of any op, int8 = 1 byte per value."""
    sizes = {t["index"]: int(np.prod(t["shape"])) for t in it.get_tensor_details()}
    peak = 0
    for op in it._get_ops_details():
        ins = [sizes.get(k, 0) for k in op["inputs"] if k >= 0]
        outs = [sizes.get(k, 0) for k in op["outputs"]]
        if op["op_name"] in ("CONV_2D", "MAX_POOL_2D", "MEAN", "FULLY_CONNECTED", "SOFTMAX", "QUANTIZE"):
            peak = max(peak, max(ins[:1] or [0]) + sum(outs))
    return peak


def c_array(blob, name, meta):
    lines = [f"// generated by classifier/export.py - do not edit",
             f"// {meta}",
             "#pragma once",
             "#include <stdint.h>",
             f"alignas(16) const unsigned char {name}[] = {{"]
    for i in range(0, len(blob), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 16]) + ",")
    lines += ["};", f"const unsigned int {name}_len = {len(blob)};", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", help="run folder (default: best CV macro-F1)")
    ap.add_argument("--sessions", nargs="+", default=["10"], help="data for calibration + agreement check")
    a = ap.parse_args()
    run = a.run or os.path.dirname(live.best_model())
    import keras
    model = keras.models.load_model(os.path.join(run, "model.keras"))
    p = pp.load_params()
    classes = p["model"]["classes"]
    X, y, _, _ = load(os.path.join(ROOT, "dataset"), a.sessions, classes)

    blob = convert(model, X)
    pf = model.predict(X, verbose=0)
    pq, (si, zi), (so, zo), it = run_tflite(blob, X)
    agree = float((pf.argmax(1) == pq.argmax(1)).mean())
    info = dict(run=run, bytes=len(blob), agreement_int8_vs_float=agree,
                accuracy_float_on_data=float((pf.argmax(1) == y).mean()),
                accuracy_int8_on_data=float((pq.argmax(1) == y).mean()),
                max_prob_abs_diff=float(np.abs(pf - pq).max()),
                input_scale=float(si), input_zero_point=int(zi), output_scale=float(so), output_zero_point=int(zo),
                macs=macs(model), activation_peak_bytes=activation_peak(it), classes=classes,
                note="accuracy_*_on_data is on the training data (final model) - it only checks the conversion; "
                     "the honest accuracy is the CV in report.json")
    with open(os.path.join(run, "model_int8.tflite"), "wb") as f:
        f.write(blob)
    meta = (f"{os.path.basename(run)}: {len(blob)} bytes, input int8 = pixel - 128 (scale {si:g}, zp {zi}), "
            f"output scale {so:g} zp {zo}, classes {classes}")
    hdr = c_array(blob, "g_model", meta)
    hdr += (f"const float g_model_out_scale = {so!r}f;\nconst int g_model_out_zero_point = {zo};\n"
            f"const char *const g_model_classes[] = {{{', '.join(chr(34) + c + chr(34) for c in classes)}}};\n"
            f"const int g_model_n_classes = {len(classes)};\n")
    with open(os.path.join(run, "model_data.h"), "w") as f:
        f.write(hdr)
    from classifier import npmodel
    npmodel.to_npz(model, os.path.join(run, "model_np.npz"), classes)     # for the twin app (no TensorFlow)
    with open(os.path.join(run, "export.json"), "w") as f:
        json.dump(info, f, indent=2)
    for k, v in info.items():
        print(f"{k:>26}: {v}")


if __name__ == "__main__":
    main()
