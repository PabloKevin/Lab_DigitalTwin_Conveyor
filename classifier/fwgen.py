"""
classifier/fwgen.py - bridge between params.json / the trained model and the ESP32 classifier firmware.

    python -m classifier.fwgen                 # writes firmware/esp32_cam_classifier/params.h and copies
                                               # model_data.h of the best run (run classifier.export first)
    python -m classifier.fwgen --run classifier/runs/<run>

Also used by the parity test: FFParams (ctypes mirror of ff_params in facefind.h) and build_pc_lib()
(compiles facefind.cpp as a PC shared library).
"""
import argparse
import ctypes
import os
import shutil
import subprocess

from classifier import preprocess as pp

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FW = os.path.join(ROOT, "firmware", "esp32_cam_classifier")

# (field, C type, value from params.json) - ORDER MUST MATCH ff_params in facefind.h
FIELDS = [
    ("downsample", "int", lambda p: p["image"]["downsample"]),
    ("win_x1", "int", lambda p: (p["image"]["window"] or [0, 0, 0, 0])[0]),
    ("win_y1", "int", lambda p: (p["image"]["window"] or [0, 0, 0, 0])[1]),
    ("win_x2", "int", lambda p: (p["image"]["window"] or [0, 0, 0, 0])[2]),
    ("win_y2", "int", lambda p: (p["image"]["window"] or [0, 0, 0, 0])[3]),
    ("chroma_gain", "float", lambda p: p["edges"]["chroma_gain"]),
    ("mode_percentile", "int", lambda p: int(p["edges"]["mode"] == "percentile")),
    ("lo", "int", lambda p: p["edges"]["lo"]),
    ("hi", "int", lambda p: p["edges"]["hi"]),
    ("hi_percentile", "float", lambda p: p["edges"]["hi_percentile"]),
    ("lo_ratio", "float", lambda p: p["edges"]["lo_ratio"]),
    ("min_edge_px", "int", lambda p: p["edges"]["min_edge_px"]),
    ("close_r", "int", lambda p: p["mask"]["close_r"]),
    ("open_r", "int", lambda p: p["mask"]["open_r"]),
    ("min_area_px", "int", lambda p: p["blob"]["min_area_px"]),
    ("max_area_px", "int", lambda p: p["blob"]["max_area_px"]),
    ("edge_margin_px", "int", lambda p: p["blob"]["edge_margin_px"]),
    ("max_side_ratio", "float", lambda p: p["blob"]["max_side_ratio"]),
    ("min_rect_fill", "float", lambda p: p["blob"]["min_rect_fill"]),
    ("side_cm_min", "float", lambda p: p["blob"]["side_cm"][0]),
    ("side_cm_max", "float", lambda p: p["blob"]["side_cm"][1]),
    ("merge_gap_cm", "float", lambda p: p["blob"]["merge_gap_cm"]),
    ("merge_max_deg", "float", lambda p: p["blob"]["merge_max_deg"]),
    ("merge_min_px", "int", lambda p: p["blob"]["merge_min_px"]),
    ("corner_probe_frac", "float", lambda p: p["blob"]["corner_probe_frac"]),
    ("min_corner_hits", "int", lambda p: p["blob"]["min_corner_hits"]),
    ("px_per_cm", "float", lambda p: p["crop"]["px_per_cm"]),
    ("input_size", "int", lambda p: p["crop"]["input_size"]),
    ("inset_frac", "float", lambda p: p["crop"]["inset_frac"]),
]


class FFParams(ctypes.Structure):
    _fields_ = [(n, ctypes.c_int if t == "int" else ctypes.c_float) for n, t, _ in FIELDS]


class FFResult(ctypes.Structure):
    _fields_ = [("status", ctypes.c_int), ("bbox", ctypes.c_int * 4), ("corners", ctypes.c_float * 8),
                ("size_cm", ctypes.c_float * 2), ("angle", ctypes.c_float), ("area_px", ctypes.c_int),
                ("n_blobs", ctypes.c_int)]


def ff_params(p):
    return FFParams(*[fn(p) for _, _, fn in FIELDS])


def params_h(p):
    d = p["decision"]
    lines = ["// generated by classifier/fwgen.py from classifier/params.json - do not edit", "#pragma once",
             '#include "facefind.h"', "", "static const ff_params FF_PARAMS = {"]
    for n, t, fn in FIELDS:
        v = fn(p)
        lines.append(f"  /* {n} */ {int(v) if t == 'int' else repr(float(v)) + 'f'},")
    lines += ["};", "",
              f"#define VOTE_N_FRAMES {int(d['n_frames'])}",
              f"#define VOTE_MIN_AGREE {int(d['min_agree'])}",
              f"#define VOTE_TAU {float(d['tau'])!r}f",
              "// destination per decision (classes order = model output order, then dudoso)"]
    dest = [p["destinations"][c] for c in p["model"]["classes"]] + [p["destinations"]["dudoso"]]
    lines.append("static const char *const DESTINATIONS[] = {" + ", ".join(f'"{x}"' for x in dest) + "};")
    return "\n".join(lines) + "\n"


def build_pc_lib(out_dir):
    """Compile facefind.cpp for the PC (g++) -> path of the shared library."""
    so = os.path.join(out_dir, "libfacefind.so")
    src = os.path.join(FW, "facefind.cpp")
    if not os.path.exists(so) or os.path.getmtime(so) < os.path.getmtime(src):
        subprocess.check_call(["g++", "-O2", "-std=c++17", "-shared", "-fPIC", "-o", so, src])
    lib = ctypes.CDLL(so)
    lib.ff_process.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_int, ctypes.c_int,
                               ctypes.POINTER(FFParams), ctypes.POINTER(FFResult), ctypes.c_void_p]
    lib.ff_process.restype = ctypes.c_int
    return lib


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", help="run folder with model_data.h (default: best run)")
    a = ap.parse_args()
    p = pp.load_params()
    with open(os.path.join(FW, "params.h"), "w") as f:
        f.write(params_h(p))
    print(f"wrote {os.path.join(FW, 'params.h')}")
    from classifier import live
    run = a.run or os.path.dirname(live.best_model())
    src = os.path.join(run, "model_data.h")
    if not os.path.exists(src):
        raise SystemExit(f"{src} missing - run: python -m classifier.export --run {run}")
    shutil.copyfile(src, os.path.join(FW, "model_data.h"))
    print(f"copied {src} -> {FW}/model_data.h")


if __name__ == "__main__":
    main()
